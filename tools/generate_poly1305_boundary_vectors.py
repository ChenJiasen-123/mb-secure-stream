"""Generate Poly1305 boundary cases with an independent big-integer oracle.

RFC 8439 section 2.5.1: direct polynomial modulo 2**130-5, rather than the
MoonBit implementation's radix-2**26 limbs. Test keys/messages only.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def oracle(key, message):
    r = int.from_bytes(key[:16], 'little') & 0x0ffffffc0ffffffc0ffffffc0fffffff
    s = int.from_bytes(key[16:], 'little')
    accumulator = 0
    for start in range(0, len(message), 16):
        block = message[start:start + 16]
        accumulator = ((accumulator + int.from_bytes(block + b'\x01', 'little')) * r) % (2**130 - 5)
    return ((accumulator + s) % 2**128).to_bytes(16, 'little')


# Sanity-check the independent oracle with the published RFC 8439 example.
assert oracle(bytes.fromhex('85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b'),
              b'Cryptographic Forum Research Group').hex() == 'a8061dc1305136c6c22b8baf0c0127a9'
lines = ['// Generated by tools/generate_poly1305_boundary_vectors.py.',
         '// Independent direct-integer RFC 8439 oracle; synthetic test keys only.',
         '///|', 'test "poly1305 independent partial-block and high-byte vectors" {']
lengths = list(range(34)) + [47, 48, 49, 63, 64, 65, 127, 128, 129]
for variant, key in enumerate([bytes([255]) * 32, bytes(range(32))]):
    for length in lengths:
        message = bytes((255 - i % 251) if variant == 0 else (i * 73 + 129) % 256 for i in range(length))
        formula = '(255 - i % 251)' if variant == 0 else '((i * 73 + 129) % 256)'
        lines += ['  {', f'    let key = hex_to_uints("{key.hex()}")',
                  f'    let message = Array::makei({length}, i => {formula}.reinterpret_as_uint())',
                  f'    assert_eq(uints_to_hex(@src.poly1305_mac(key, message)), "{oracle(key, message).hex()}")',
                  '  }']
lines += ['}', '']
(ROOT / 'crypto/mb-poly1305/src/boundaries_test.mbt').write_bytes('\n'.join(lines).encode('utf-8'))
print(f'Generated {len(lengths) * 2} independent Poly1305 boundary vectors')
