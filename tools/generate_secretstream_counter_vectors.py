"""Generate test-only counter-wrap vectors from independent PyNaCl/libsodium.

The state layout is explicitly pinned to libsodium's public C header:
32 key bytes, 12 nonce bytes, 8 padding bytes. This does not expose a public
fixed-header sender or state-mutation API in the MoonBit library.
"""
import json
from pathlib import Path

import nacl
from nacl.bindings.crypto_secretstream import ffi
from nacl.bindings import (
    crypto_secretstream_xchacha20poly1305_state as State,
    crypto_secretstream_xchacha20poly1305_init_pull as init_pull,
    crypto_secretstream_xchacha20poly1305_push as push,
    crypto_secretstream_xchacha20poly1305_pull as pull,
)

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'crypto/mb-secretstream'
key, header = bytes(range(32)), bytes(range(24))
sender, reader = State(), State()
for state in (sender, reader):
    init_pull(state, header, key)
    raw = ffi.buffer(state.statebuf)
    if len(raw) != 52 or bytes(raw[32:36]) != b'\x01\x00\x00\x00':
        raise RuntimeError('Unexpected libsodium state layout; review before regeneration')
    # Reach the boundary without processing 2**32 frames. Test fixture only.
    raw[32:36] = (0xFFFFFFFE).to_bytes(4, 'little')

vectors = []
for index, tag in enumerate([0, 0, 0, 2, 0, 3]):
    message = bytes((index + j * 37) % 256 for j in range(index * 17))
    aad = bytes((index + j * 11) % 256 for j in range(index * 3))
    frame = push(sender, message, aad, tag)
    if pull(reader, frame, aad) != (message, tag):
        raise RuntimeError('Oracle roundtrip failed')
    sent, received = bytes(ffi.buffer(sender.statebuf)), bytes(ffi.buffer(reader.statebuf))
    if sent[:44] != received[:44]:
        raise RuntimeError('Oracle sender/reader states differ')
    vectors.append(dict(message=message.hex(), aad=aad.hex(), tag=tag,
                        frame=frame.hex(), nextKey=sent[:32].hex(), nextNonce=sent[32:44].hex()))

fixture = dict(oracle=f'PyNaCl {nacl.__version__} bundled libsodium',
               layoutReference='https://github.com/jedisct1/libsodium/blob/89e500718da7e1fc90e168bd88e18d1060f54db3/src/libsodium/include/sodium/crypto_secretstream_xchacha20poly1305.h',
               key=key.hex(), header=header.hex(), initialCounter=0xFFFFFFFE,
               testOnlyForcedCounter=True, vectors=vectors)
(PACKAGE / 'fixtures/counter-wrap.json').write_text(json.dumps(fixture, indent=2) + '\n', encoding='utf-8')

def arr(value):
    return f'fixture_hex("{value}")'

lines = ['// Generated by tools/generate_secretstream_counter_vectors.py.',
         '// Test-only state positioning; independent libsodium ciphertext and next states.',
         '///|', 'test "libsodium automatic rekey at 32-bit counter wrap" {',
         f'  let key = {arr(key.hex())}', f'  let header = {arr(header.hex())}',
         '  let writer = init_pull(key, header).unwrap()',
         '  let reader = init_pull(key, header).unwrap()',
         '  for i in 0..<4 {',
         '    writer.nonce[i] = if i == 0 { 254U } else { 255U }',
         '    reader.nonce[i] = writer.nonce[i]', '  }']
for vector in vectors:
    lines += ['  {', f'    let message = {arr(vector["message"])}',
              f'    let aad = {arr(vector["aad"])}', f'    let frame = {arr(vector["frame"])}',
              f'    let expected_key = {arr(vector["nextKey"])}',
              f'    let expected_nonce = {arr(vector["nextNonce"])}',
              '    let old_key = reader.key.copy()', '    let old_nonce = reader.nonce.copy()',
              '    let damaged = frame.copy()', '    damaged[damaged.length() - 1] = damaged[damaged.length() - 1] ^ 1U',
              '    assert_true(reader.pull(damaged, aad) is Err(_))',
              '    assert_eq(reader.key, old_key)', '    assert_eq(reader.nonce, old_nonce)',
              f'    assert_eq(push(writer, message, aad, {vector["tag"]}U).unwrap(), frame)',
              f'    assert_eq(reader.pull(frame, aad).unwrap(), (message, {vector["tag"]}U))',
              '    assert_eq(writer.key, expected_key)', '    assert_eq(reader.key, expected_key)',
              '    assert_eq(writer.nonce, expected_nonce)', '    assert_eq(reader.nonce, expected_nonce)',
              '  }']
lines += ['  assert_eq(reader.finish(), Ok(()))', '}', '']
(PACKAGE / 'src/counter_wrap_wbtest.mbt').write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(vectors)} deterministic counter-wrap oracle frames and states')
