"""Independent PyNaCl/libsodium oracle. Install tools/requirements-dev.txt first."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import nacl
from nacl.bindings import (
    crypto_secretstream_xchacha20poly1305_state as State,
    crypto_secretstream_xchacha20poly1305_init_push as init_push,
    crypto_secretstream_xchacha20poly1305_init_pull as init_pull,
    crypto_secretstream_xchacha20poly1305_push as push,
    crypto_secretstream_xchacha20poly1305_pull as pull,
)

key = bytes(range(32))
sender = State()
header = init_push(sender, key)
reader = State()
init_pull(reader, header, key)
vectors = []
lengths = [0, 1, 15, 16, 17, 63, 64, 65, 255, 4096, 7, 19]
for i, length in enumerate(lengths):
    message = bytes((j * 37 + i) % 256 for j in range(length))
    aad = bytes((j * 13 + i) % 256 for j in range(i * 3))
    tag = 3 if i == len(lengths) - 1 else (2 if i == 5 else (1 if i == 2 else 0))
    frame = push(sender, message, aad, tag)
    assert pull(reader, frame, aad) == (message, tag)
    vectors.append(dict(message=message.hex(), aad=aad.hex(), tag=tag, frame=frame.hex()))

fixture = dict(oracle=f'PyNaCl {nacl.__version__} bundled libsodium', key=key.hex(), header=header.hex(), vectors=vectors)
package = ROOT / 'crypto/mb-secretstream'
(package / 'fixtures').mkdir(parents=True, exist_ok=True)
(package / 'fixtures/libsodium.json').write_text(json.dumps(fixture, indent=2) + '\n', encoding='utf-8')

def arr(value):
    return 'fixture_hex("' + value.hex() + '")'

lines = ['// Generated by tools/generate_secretstream_vectors.py using independent libsodium.',
         '///|', 'fn fixture_hex(s : String) -> Array[UInt] {',
         '  let bytes = @hex.decode(s[:]) catch { _ => abort("Invalid fixture") }',
         '  Array::makei(bytes.length(), i => bytes[i].to_int().reinterpret_as_uint())', '}', '///|',
         'test "libsodium compatibility encrypt and decrypt across boundaries and rekey" {',
         f'  let key = {arr(key)}', f'  let header = {arr(header)}',
         '  let writer = init_pull(key, header).unwrap()', '  let reader = init_pull(key, header).unwrap()']
for v in vectors:
    message, aad, frame = (bytes.fromhex(v[k]) for k in ('message', 'aad', 'frame'))
    lines += ['  {', f'    let message = {arr(message)}', f'    let aad = {arr(aad)}', f'    let frame = {arr(frame)}',
              f'    assert_eq(push(writer, message, aad, {v["tag"]}U).unwrap(), frame)',
              f'    assert_eq(reader.pull(frame, aad).unwrap(), (message, {v["tag"]}U))', '  }']
lines += ['  assert_eq(reader.finish(), Ok(()))', '}', '']
first, second = vectors[:2]
lines += ['///|', 'test "reject tampering aad replay reorder and truncation without advancing" {',
          f'  let key = {arr(key)}', f'  let header = {arr(header)}',
          f'  let first = {arr(bytes.fromhex(first["frame"]))}',
          f'  let second = {arr(bytes.fromhex(second["frame"]))}',
          f'  let second_aad = {arr(bytes.fromhex(second["aad"]))}',
          '  let reader = init_pull(key, header).unwrap()',
          '  assert_true(reader.finish() is Err(_))',
          '  assert_true(reader.pull(second, second_aad) is Err(_))',
          '  assert_true(reader.pull(first, [1U]) is Err(_))',
          '  assert_true(reader.pull([0U], []) is Err(_))',
          '  for i in 0..<first.length() {',
          '    let changed = first.copy()', '    changed[i] = changed[i] ^ 1U',
          '    assert_true(reader.pull(changed, []) is Err(_))', '  }',
          '  assert_eq(reader.pull(first, []).unwrap(), ([], 0U))',
          '  assert_true(reader.pull(first, []) is Err(_))',
          '  assert_eq(reader.pull(second, second_aad).unwrap(), ([1U], 0U))',
          '  assert_true(reader.finish() is Err(_))',
          '  let wrong_key = key.copy()', '  wrong_key[0] = wrong_key[0] ^ 1U',
          '  assert_true(init_pull(wrong_key, header).unwrap().pull(first, []) is Err(_))',
          '  assert_true(init_pull([], header) is Err(_))',
          '  assert_true(init_pull(key, []) is Err(_))',
          '  let invalid_header = header.copy()', '  invalid_header[0] = 256U',
          '  assert_true(init_pull(key, invalid_header) is Err(_))', '}', '']
lines += ['///|', 'test "final is terminal and oversized input is rejected" {',
          f'  let key = {arr(key)}', f'  let header = {arr(header)}',
          '  let writer = init_pull(key, header).unwrap()',
          '  let reader = init_pull(key, header).unwrap()',
          '  let frame = push(writer, [42U], [], 3U).unwrap()',
          '  assert_eq(reader.pull(frame, []).unwrap(), ([42U], 3U))',
          '  assert_eq(reader.finish(), Ok(()))',
          '  assert_true(reader.pull(frame, []) is Err(_))',
          '  assert_true(push(writer, [], [], 0U) is Err(_))',
          '  let fresh = init_pull(key, header).unwrap()',
          '  assert_true(fresh.pull(Array::make(1048594, 0U), []) is Err(_))',
          '  assert_true(fresh.pull([256U], []) is Err(_))',
          '  assert_true(push(fresh, [], [], 4U) is Err(_))', '}', '']
(package / 'src/interop_wbtest.mbt').write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(vectors)} independent sequential vectors, including REKEY and FINAL')
